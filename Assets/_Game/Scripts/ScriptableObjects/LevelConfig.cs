using System;
using UnityEngine;

namespace EmberThrone.Data
{
    [CreateAssetMenu(fileName = "Level_000", menuName = "EmberThrone/Level Config", order = 1)]
    public class LevelConfig : ScriptableObject
    {
        [Header("─── Identity ───")]
        [Tooltip("Unique level ID (1-based, sequential)")]
        public int levelId;

        [Tooltip("Parent chapter ID (1-10)")]
        [Range(1, 10)]
        public int chapterId;

        [Header("─── Grid ───")]
        [Tooltip("Grid width in tiles")]
        [Range(5, 9)]
        public int gridWidth = 9;

        [Tooltip("Grid height in tiles")]
        [Range(5, 9)]
        public int gridHeight = 9;

        [Tooltip("Number of available colors (3-5)")]
        [Range(3, 5)]
        public int availableColors = 5;

        [Tooltip("Gravity direction for tile falling")]
        public GravityDirection gravityDirection = GravityDirection.Down;

        [Header("─── Moves & Time ───")]
        [Tooltip("Maximum moves allowed (must be > 0)")]
        [Min(1)]
        public int maxMoves = 25;

        [Tooltip("Target time in seconds for speed runner tasks. 0 = no timer. TECH-001 §13")]
        [Min(0)]
        public int targetTimeSeconds = 0;

        [Header("─── Goals ───")]
        [Tooltip("Level objectives — all must be completed to win")]
        public LevelGoal[] goals;

        [Header("─── Obstacles ───")]
        [Tooltip("Obstacles placed on the board at level start")]
        public ObstaclePlacement[] obstacles;

        [Header("─── Special Pieces ───")]
        [Tooltip("Weight multipliers for special piece generation. Default = 1.0")]
        public SpecialPieceWeight[] specialPieceWeights;

        [Header("─── Difficulty ───")]
        [Tooltip("Difficulty band — LVL-DESIGN-001")]
        public DifficultyBand difficultyBand = DifficultyBand.Tutorial;

        [Tooltip("Expected fail rate for this difficulty band")]
        [Range(0f, 1f)]
        public float expectedFailRate = 0f;

        [Header("─── Generation Metadata ───")]
        [Tooltip("Was this level generated by Grammar Simulator?")]
        public bool isGrammarGenerated = true;

        [Tooltip("Has this level been manually overridden?")]
        public bool isOverridden = false;

        [Tooltip("Designer notes for manual overrides")]
        [TextArea(2, 4)]
        public string overrideNote = "";

        [Tooltip("Solvability rate from Grammar Simulator (1000 attempts)")]
        [Range(0f, 1f)]
        public float solvabilityRate = 1f;

        [Tooltip("Is this a critical level? (5th, 10th, 15th in each chapter)")]
        public bool isCriticalLevel = false;

#if UNITY_EDITOR
        private void OnValidate()
        {
            if (gridWidth < 5 || gridWidth > 9)
                Debug.LogWarning($"[LevelConfig] Level {levelId}: gridWidth {gridWidth} out of range [5,9]");

            if (gridHeight < 5 || gridHeight > 9)
                Debug.LogWarning($"[LevelConfig] Level {levelId}: gridHeight {gridHeight} out of range [5,9]");

            if (availableColors < 3 || availableColors > 5)
                Debug.LogWarning($"[LevelConfig] Level {levelId}: availableColors {availableColors} out of range [3,5]");

            if (maxMoves <= 0)
                Debug.LogError($"[LevelConfig] Level {levelId}: maxMoves must be > 0");

            if (goals == null || goals.Length == 0)
                Debug.LogWarning($"[LevelConfig] Level {levelId}: no goals defined");

            int posInChapter = ((levelId - 1) % 15) + 1;
            if (posInChapter == 5 || posInChapter == 10 || posInChapter == 15)
            {
                if (!isCriticalLevel)
                    Debug.LogWarning($"[LevelConfig] Level {levelId}: position {posInChapter} in chapter should be marked as critical level");
            }
        }
#endif
    }

    [Serializable]
    public struct LevelGoal
    {
        public GoalType goalType;
        public int targetCount;

        [Tooltip("Optional: specific color/obstacle for targeted goals")]
        public int targetVariant;
    }

    [Serializable]
    public struct ObstaclePlacement
    {
        public ObstacleType obstacleType;
        public int count;

        [Tooltip("Optional: specific grid positions. Empty = random placement")]
        public Vector2Int[] positions;
    }

    [Serializable]
    public struct SpecialPieceWeight
    {
        public SpecialPieceType pieceType;

        [Tooltip("Weight multiplier. 1.0 = normal, 0 = disabled")]
        [Range(0f, 3f)]
        public float weight;
    }

    public enum GoalType
    {
        CollectColor,
        DestroyObstacle,
        ScoreTarget,
        UseSpecialPiece,
    }

    public enum ObstacleType
    {
        None = 0,
        Crate = 1,
        IceCrate = 2,
        Chained = 3,
        Stone = 4,
        FireBox = 5,
        WireCage = 6,
        Crystal = 7,
    }

    public enum SpecialPieceType
    {
        RocketHorizontal,
        RocketVertical,
        Bomb,
        TNT,
        Rainbow,
    }

    public enum DifficultyBand
    {
        Tutorial,
        Onboarding,
        CoreCasual,
        MidChallenge,
        HardWall,
        Expert,
    }

    public enum GravityDirection
    {
        Down,
        Up,
        Left,
        Right,
    }
}
